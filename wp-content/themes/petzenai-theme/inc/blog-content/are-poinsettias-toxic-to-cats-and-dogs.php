<h2>Are Poinsettias Toxic to Cats? The Short Answer</h2>
<p>The ASPCA lists the poinsettia (<em>Euphorbia pulcherrima</em>) as toxic to dogs, cats and horses. It also says the plant is “generally over-rated in toxicity”. Pet Poison Helpline rates it as mildly toxic to both cats and dogs.</p>
<p>The problem is the white, milky sap. It contains irritating chemicals that affect the mouth, stomach and skin. Most pets only nibble a leaf or two because the taste and the irritation put them off. The signs are usually mild and go away on their own.</p>
<p>So a poinsettia is not a reason to panic. It is still a good idea to keep it out of reach, especially if you have a cat that chews plants or a puppy that chews everything.</p>

<h2>Is a Poinsettia Poisonous to Dogs?</h2>
<p>Dogs react in much the same way as cats. A dog that chews a poinsettia may drool, vomit or have an upset stomach for a short time. Because dogs can eat more plant material in one go, they may be sicker than a cat that took a single bite, but serious problems are still uncommon.</p>
<p>Take care with a puppy or a large dog that destroys the whole plant. The potting soil, foil wrapping, plastic pot or decorative picks can cause their own problems, such as stomach upset or a blockage.</p>

