<h2>What to Do If Your Pet Chewed a Poinsettia</h2>
<ol>
<li><strong>Remove the plant</strong> and any fallen leaves so your pet cannot eat more.</li>
<li><strong>Check your pet’s mouth</strong> and gently wipe away any plant pieces. You can offer fresh water.</li>
<li><strong>Wash off sap</strong> from the fur or skin with mild soap and water. If sap got into an eye, rinse it gently with clean water.</li>
<li><strong>Do not make your pet vomit</strong> unless a vet tells you to.</li>
<li><strong>Watch your pet</strong> for the next few hours. Mild drooling or one bout of vomiting is common and usually settles.</li>
<li><strong>Call your vet</strong> if vomiting or diarrhoea keeps going, your pet will not eat or drink, seems very tired, or you are not sure which plant they ate.</li>
</ol>
