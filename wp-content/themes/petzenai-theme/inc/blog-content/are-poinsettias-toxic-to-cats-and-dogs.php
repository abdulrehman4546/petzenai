<h2>Frequently Asked Questions</h2>

<h3>Can a poinsettia kill a cat?</h3>
<p>It is very unlikely. Poison-control sources describe poinsettias as mildly toxic and say their danger is often exaggerated. Most cats only have drooling or vomiting that settles on its own. Call a vet if signs are severe or do not stop.</p>

<h3>How much poinsettia is toxic to a dog?</h3>
<p>There is no set amount, but even a small bite can cause drooling or vomiting because the sap is irritating. Eating a lot of the plant makes stomach upset more likely. Call your vet if your dog ate a large amount or seems unwell.</p>

<h3>What should I do if my cat licked poinsettia sap?</h3>
<p>Wipe the sap off the fur and skin with mild soap and water, give your cat fresh water and watch for drooling or vomiting. Most cats are fine within a few hours.</p>

<h3>Which Christmas plants are most dangerous to pets?</h3>
<p>For cats, true lilies and daylilies are the most dangerous, because they can cause kidney failure. Mistletoe, holly and amaryllis are also toxic to cats and dogs. Poinsettias are at the milder end.</p>

<h3>Is the Christmas cactus safe for cats and dogs?</h3>
<p>The ASPCA lists the Christmas cactus as non-toxic to cats and dogs. Eating a lot of any plant can still cause mild stomach upset.</p>

<h3>Are white or pink poinsettias any safer?</h3>
<p>No. The colour is just the variety. All poinsettias have the same irritating sap, so treat them all the same way.</p>

