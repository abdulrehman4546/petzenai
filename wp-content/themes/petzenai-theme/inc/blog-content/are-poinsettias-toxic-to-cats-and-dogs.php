<h3>Why lilies are the real danger for cats</h3>
<p>Lilies are popular in winter bouquets and arrangements, and they are far more dangerous to cats than poinsettias. According to the FDA, every part of a true lily or daylily is toxic to cats, including the leaves, petals, pollen and even the water in the vase. A cat can be poisoned just by licking pollen off its fur.</p>
<p>Early signs include drooling, vomiting, low energy and not eating. Kidney failure can follow within 24 to 72 hours. The FDA notes that if treatment is delayed by 18 hours or more, the kidney damage is generally permanent. If your cat has touched or chewed a lily, contact a vet straight away, even if your cat seems fine.</p>
<p>Not every plant called a “lily” acts this way. Peace lilies and calla lilies irritate the mouth but do not cause kidney failure. Lily of the valley is a different danger, because it can affect the heart in both cats and dogs.</p>

<h2>Tips for Keeping Holiday Plants and Pets Apart</h2>
<ul>
<li><strong>Skip lilies if you have a cat.</strong> Ask florists to leave them out of bouquets, and check gift arrangements before bringing them inside.</li>
<li><strong>Put plants up high</strong> or in a room your pet cannot enter. Remember that cats can jump onto most shelves.</li>
<li><strong>Clear up fallen leaves, berries and petals</strong> every day. Holly berries and mistletoe berries drop easily.</li>
<li><strong>Consider artificial plants</strong> for mistletoe and holly, but make sure pets cannot chew small plastic parts.</li>
<li><strong>Offer pet-safe alternatives</strong> to chew, like a toy or cat grass, so your pet is less tempted by decorations.</li>
<li><strong>Know the plant names</strong> in your home. If something is eaten, your vet will want to know exactly what it was.</li>
</ul>
