<h2>Why Tinsel and Ribbon Are an Emergency</h2>
<p>Vets call swallowed tinsel, ribbon and string a <strong>linear foreign body</strong>. One end can catch under the tongue or in the stomach while the rest moves into the intestines. As the gut contracts, the string can saw through the intestinal wall. This often needs surgery.</p>
<p>If you see string, ribbon or tinsel hanging from your cat’s mouth or bottom, <strong>do not pull it</strong>. It may be anchored inside, and pulling can cause serious internal damage. Call your vet straight away.</p>

<h2>Warning Signs That Need a Vet</h2>
<p>Call your vet or an emergency clinic if your cat shows any of these after time near the tree:</p>
<ul>
<li>Repeated vomiting, or trying to vomit without bringing anything up</li>
<li>Not eating, hiding or being unusually quiet</li>
<li>Diarrhoea or a swollen, sore belly</li>
<li>String, ribbon or tinsel visible in the mouth or at the bottom</li>
<li>Drooling, mouth sores or burns, or not wanting to eat after chewing a cord</li>
<li>Coughing or difficulty breathing, which can follow an electrical injury</li>
<li>Bleeding from the mouth or paws after an ornament breaks</li>
</ul>
<p>Cats can hide illness and may keep eating for a while even with a blockage, so do not wait for things to get worse. In the United States, the ASPCA Animal Poison Control Center is (888) 426-4435 and the Pet Poison Helpline is (855) 764-7661; a fee may apply. Our <a href="/tools/pet-poison-emergency-guide/">pet poison emergency guide</a> explains what to do first. For holiday plants, food and visitors, see our <a href="/tools/holiday-pet-safety-guide/">holiday pet safety guide</a>.</p>

<h2>Frequently Asked Questions</h2>

<h3>Are Christmas trees toxic to cats?</h3>
<p>Fir, pine and spruce trees are generally considered mildly toxic. Their oils are present in low amounts, but eating needles can irritate the mouth and stomach and cause vomiting or drooling. Large amounts can cause a blockage or puncture, because needles do not digest well.</p>

<h3>Is Christmas tree water bad for cats?</h3>
<p>Plain tree water usually causes only mild stomach upset, but some preservatives and additives can cause vomiting or diarrhoea. Standing water can grow bacteria, so use plain water, change it often and cover the stand.</p>

<h3>What should I do if my cat eats tinsel?</h3>
<p>Call your vet now, even if your cat seems fine, and never pull on it. See the tinsel section above.</p>

<h3>How do I stop my cat climbing the Christmas tree?</h3>
<p>Leave the bottom branches bare at first, place the tree away from furniture, and give your cat a cat tree or perch nearby. A playpen around the tree is the most reliable option for determined climbers.</p>

<h3>Should I get a real or artificial tree if I have a cat?</h3>
<p>An artificial tree removes the needles, sap and water, so it is often the safer choice. Either type still needs anchoring and safe decorations.</p>

