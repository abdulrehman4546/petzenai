<h2>Frequently Asked Questions</h2>

<h3>Is Christmas tree water bad for cats?</h3>
<p>Plain tree water usually causes only mild stomach upset. The ASPCA notes that standing tree water can grow bacteria that cause nausea or diarrhoea, and some preservatives can upset the stomach. Use plain water, cover the stand and offer a fresh water bowl elsewhere.</p>

<h3>What should I do if my cat eats tinsel?</h3>
<p>Call your vet or an emergency clinic straight away, even if your cat seems fine, because tinsel can block the intestines. If a strand is hanging from the mouth or bottom, do not pull it, since it may be caught inside. Do not try to make your cat vomit.</p>

<h3>How do I stop my cat climbing the Christmas tree?</h3>
<p>Leave the bottom branches bare for the first few days, keep the tree away from furniture your cat can jump from, and put a cat tree or window perch nearby. For a determined climber, a playpen or gate around the tree is the most reliable option.</p>

<h3>Should I get a real or artificial tree if I have a cat?</h3>
<p>An artificial tree is often the safer choice with a cat, because it has no sap, needles or water. It is lighter, though, so it still needs anchoring at the top and base, and you should watch for chewing on the plastic branches.</p>

<h3>Can I use citrus or peppermint spray to keep my cat away from the tree?</h3>
<p>It is best not to. Many essential oils, including citrus and peppermint oils, can be harmful to cats, and your cat may brush the tree and lick the residue from its fur. A tree collar, foil under the skirt or a playpen is safer.</p>

<h3>Is it safe to leave Christmas lights on with a cat in the house?</h3>
<p>It is safest to unplug tree lights whenever nobody is at home to watch, including overnight and when you go out. A cat that chews a live cord can suffer mouth burns, an electric shock or breathing problems. Keep cords covered and check them for bite marks.</p>

<h3>When should I decorate the tree after putting it up?</h3>
<p>Many owners leave the bare, undecorated tree standing for a few days first, so the cat can explore and lose interest while there is nothing to break or swallow. Then add lights, upper ornaments and, last, the lower branches.</p>

<h3>What are the safest ornaments for a home with cats?</h3>
<p>The safest ornaments are soft or unbreakable, such as felt, cloth, straw or wood, tied on with cloth loops instead of metal hooks and large enough not to be swallowed. Avoid glass, ceramic, salt dough and food ornaments, and keep fragile pieces high up.</p>

