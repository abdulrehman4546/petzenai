<p>Anchor it at the top and base, cover the water well and vacuum fallen needles every day. If your cat gets sap on its fur, Pet Poison Helpline advises washing it off promptly so it is not licked off and swallowed.</p>

<h3>How do you keep cats out of a fake Christmas tree?</h3>
<p>Anchor it to the wall or ceiling, because artificial trees are light and easy to pull over, and leave the lower branches bare at first. Watch for chewing: the Merck Veterinary Manual lists swallowed foreign objects among the causes of gut obstruction, and bitten-off plastic counts.</p>

