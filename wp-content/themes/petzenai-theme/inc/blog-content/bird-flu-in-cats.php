<h2>What to Do If You Suspect Bird Flu</h2>
<ol>
<li><strong>Phone your vet first.</strong> Cornell advises calling rather than turning up with the cat, so the clinic can prepare and protect other animals and staff.</li>
<li><strong>Tell the vet about possible exposure.</strong> Mention raw food or treats (including freeze-dried raw), raw milk, hunting birds, or contact with farms or farm workers. If possible, keep the food packaging so the lot number can be checked.</li>
<li><strong>Keep the cat apart.</strong> Isolate the sick cat from other pets and keep it from close contact with people, including licking faces.</li>
<li><strong>Wash your hands</strong> with soap and water after touching the cat, its bowls or its litter box.</li>
<li><strong>Watch your own health.</strong> The CDC advises people in contact with an infected animal to watch for fever and other signs and to contact a doctor if they become ill.</li>
</ol>
