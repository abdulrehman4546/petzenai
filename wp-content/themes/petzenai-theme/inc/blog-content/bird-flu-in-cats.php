<h2>What Is Bird Flu in Cats?</h2>
<p>Bird flu (avian influenza) mainly spreads among wild birds and poultry. The virus behind the current outbreak is a highly pathogenic H5N1 strain known as clade 2.3.4.4b. It has also been found in US dairy cattle, which brought it closer to farms, milk and the food supply.</p>
<p>Cats are especially sensitive to H5N1. The FDA notes that domestic cats, along with wild cats such as lynx and mountain lions, are particularly vulnerable. The Cornell Feline Health Center says that up to 70% of infected cats die of their infections.</p>
<p>The USDA describes cats as “typically dead-end hosts” for this virus. That means an infected cat is not usually a big part of passing the virus on to other animals.</p>

<h2>How Cats Catch Bird Flu</h2>
<p>According to the CDC, Cornell and the FDA, cats have been infected through:</p>
<ul>
<li><strong>Raw pet food</strong>, especially raw poultry-based food, including some commercially sold frozen raw cat foods</li>
<li><strong>Raw (unpasteurised) milk</strong> from infected cows</li>
<li><strong>Raw or undercooked meat or poultry</strong></li>
<li><strong>Wild birds</strong>, when a cat hunts, eats or touches a sick or dead bird</li>
<li><strong>Infected farms</strong>, including dairy and poultry farms and their surroundings</li>
<li><strong>Contaminated clothing, shoes or items</strong> brought home by people who work with infected animals</li>
</ul>
<p>The CDC says most US cat infections have been linked to affected farms, with some linked to raw pet food and raw milk. It also notes that, while rare, indoor-only cats can be infected, likely through people or contaminated items.</p>

