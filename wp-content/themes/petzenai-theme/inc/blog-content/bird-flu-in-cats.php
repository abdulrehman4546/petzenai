<h2>Raw Food and Bird Flu</h2>
<p>Raw food is the risk owners can control most directly. Several raw cat foods in the US have been linked to H5N1 in cats, including products from Northwest Naturals, Wild Coast Raw, Savage Cat Food and RAWR, according to Cornell and FDA notices. In one case, in September 2025, the FDA reported that a cat in San Francisco became ill and was euthanised after eating RAWR Raw Cat Food Chicken Eats, and the virus in the cat was linked to the same food lots.</p>
<p>In January 2025 the FDA told cat and dog food makers covered by its animal food safety rules that, if they use uncooked or unpasteurised poultry or cattle ingredients, they must reanalyse their food safety plans and treat H5N1 as a known or reasonably foreseeable hazard. The FDA reissued this reminder in September 2025, ahead of autumn bird migration. The FDA also notes that heat inactivates the virus, which is why thoroughly cooked food is the safer choice.</p>
<p>What this means for you:</p>
<ul>
<li>The CDC advises: do not feed pets raw pet food or raw milk.</li>
<li>Cornell also advises against freeze-dried raw foods and treats.</li>
<li>Cooked, canned and other heat-treated cat foods avoid the main raw-food risk.</li>
<li>If you switch, change food gradually to avoid stomach upset.</li>
</ul>
<p>If you feed raw now and want to understand the trade-offs, read our <a href="/tools/cat-raw-diet-guide/">cat raw diet guide</a> alongside the advice above.</p>

<h2>Can People Catch It From Cats?</h2>
<p>The risk to most people is low. The CDC states that the current public health risk from bird flu is low, and that human infection from pets is rare, mostly after long, unprotected exposure to an infected animal.</p>
<p>There is some evidence it can happen. In May 2026 the CDC published a report on 19 sick cats in Los Angeles County, California, that had been fed raw milk, raw meat or raw pet food between late 2024 and early 2025. Of 25 exposed people who had blood tests, one veterinary professional, who had treated an infected cat without eye or breathing protection, had antibodies to H5N1. The CDC described this as evidence of <em>possible</em> cat-to-human transmission. The person never became ill and no further spread was reported.</p>
<p>Simple habits lower the risk further: wash your hands after handling your cat, food bowls, raw pet food or the litter box, and keep a sick cat away from your face. Our <a href="/tools/zoonotic-diseases-guide/">zoonotic diseases guide</a> covers other infections that pass between pets and people.</p>

<h2>Prevention Checklist</h2>
<ul>
<li>Do not feed raw meat, raw pet food, freeze-dried raw treats or raw milk.</li>
<li>Keep your cat indoors, or supervise time outside, so it cannot hunt or eat birds.</li>
<li>Keep cats away from poultry, dairy cows and farm buildings.</li>
<li>If you work with poultry, cattle or wild birds, change clothes and shoes and wash your hands before touching your cat.</li>
<li>Check pet food recall notices from the FDA and your food brand.</li>
<li>Wash hands and clean surfaces after handling any pet food.</li>
<li>Call your vet promptly if your cat develops fever, stops eating or shows any neurological signs.</li>
</ul>
<p>Cornell notes there is currently no H5N1 vaccine for cats, so avoiding exposure is the main protection.</p>

<h2>Frequently Asked Questions</h2>

<h3>Can cats get bird flu?</h3>
<p>Yes. Cats are highly sensitive to H5N1 bird flu and often become very ill. Infections have been linked to raw food, raw milk, wild birds and infected farms.</p>

<h3>What are the first symptoms of bird flu in cats?</h3>
<p>Early signs are fever, tiredness and loss of appetite. They can quickly progress to eye and nose discharge, breathing problems and neurological signs such as tremors, seizures, stumbling or blindness.</p>

<h3>Can indoor cats get bird flu?</h3>
<p>It is rare, but the CDC says it is possible, usually through contaminated food, raw milk, or people and items that carried the virus inside. Feeding cooked or commercially heat-treated food removes the biggest indoor risk.</p>

<h3>Is bird flu in cats still a risk in 2026?</h3>
<p>Yes. The FDA reissued its H5N1 reminder to pet food makers in September 2025, the USDA keeps a public list of infected mammals, and the CDC published new findings on cats and people in May 2026. Check FDA and USDA pages for the latest cases and recalls.</p>

<h3>Is there a treatment for bird flu in cats?</h3>
<p>There is no specific cure or cat vaccine. A vet can test your cat and give supportive care, so contact one as soon as you notice signs.</p>

<h3>Can humans get bird flu from cats?</h3>
<p>It is rare and the risk to the public is low, according to the CDC. One CDC report found antibodies in a vet worker after treating an infected cat, which it called possible cat-to-human transmission. Good hygiene and keeping sick cats away from your face reduce the risk.</p>

