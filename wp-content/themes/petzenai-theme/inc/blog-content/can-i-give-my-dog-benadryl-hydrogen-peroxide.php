<h2>Frequently Asked Questions</h2>

<h3>How much Benadryl can I give my dog?</h3>
<p>We deliberately don't give an amount, and you should be wary of any page that does without knowing your dog. Whether diphenhydramine is appropriate, and how much, depends on your dog's weight, age, health, other medications and the exact product. Your vet will calculate it for your dog and tell you how often, if at all.</p>

<h3>What kind of Benadryl is safe for dogs?</h3>
<p>The only product a vet would consider is one whose single active ingredient is diphenhydramine, and only after they've confirmed it suits your dog. Avoid anything with a decongestant (often marked "-D"), acetaminophen, or "cold and flu" labeling, and check inactive ingredients for xylitol or alcohol. Read the label to your vet before giving anything.</p>

<h3>How much hydrogen peroxide do I give my dog to make it throw up?</h3>
<p>Don't give any until a vet or animal poison control specialist has told you to. Often the right answer is not to induce vomiting at all; when it is, the specialist will tell you exactly what to use and how much for your dog. Call the ASPCA Animal Poison Control Center at (888) 426-4435 or Pet Poison Helpline at (855) 764-7661 first.</p>

<h3>Should I make my dog throw up if it ate chocolate, grapes or something else toxic?</h3>
<p>Only if a vet or poison control tells you to. Whether vomiting helps depends on what was eaten, how much, how long ago and how your dog is doing now. Gather the packaging and call straight away, even if your dog seems fine, because some toxins act slowly.</p>

<h3>My dog got stung by a bee. Can I give it Benadryl?</h3>
<p>For a single sting with mild local swelling, call your vet and ask. If the swelling is spreading quickly, especially around the face or throat, or your dog is struggling to breathe, vomiting or weak, that is anaphylaxis. Go to the nearest vet immediately rather than treating at home.</p>

<h3>Can I use hydrogen peroxide to make my cat throw up?</h3>
<p>No. Pet Poison Helpline states there is no safe way to induce vomiting in cats at home, and peroxide can cause serious ulceration of a cat's stomach and esophagus. Call your vet or a poison control line instead.</p>

