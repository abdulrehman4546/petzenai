<h2>Decorations and the Home</h2>
<ul>
<li><strong>Candles and jack-o’-lanterns.</strong> A wagging tail can knock over a flame. Use battery or LED lights, and keep cords out of reach, since chewing on them can cause burns or shocks.</li>
<li><strong>Artificial cobwebs.</strong> Pets, especially cats, can get tangled or swallow the fibre.</li>
<li><strong>Glow sticks.</strong> They taste bitter and often cause drooling and a lot of fuss, and chewed glow sticks should be reported to a vet.</li>
<li><strong>Pumpkins.</strong> A small amount of plain pumpkin is fine for most pets, but carved pumpkins left outside can grow mould, which is not safe to eat.</li>
<li><strong>Batteries and small props.</strong> Keep these out of reach, because they can be swallowed.</li>
</ul>

<h2>The Doorbell, Visitors and Escapes</h2>
<p>For many pets, the biggest Halloween problem is not candy but the constant knocking, strange costumes and a front door that keeps opening. Frightened pets bolt.</p>
<ul>
<li>Put your pet in a quiet, comfortable room with the door closed, and add a fan or soft music to cover noise. You can find more ideas in our <a href="/tools/pet-noise-phobia-guide/">guide to noise sensitivity in pets</a>.</li>
<li>If you answer the door, use a baby gate or leash so your pet cannot slip out.</li>
<li>Check that your pet’s ID tag is current and that the microchip details are up to date. Our <a href="/tools/pet-microchipping-guide/">microchipping guide</a> explains how.</li>
<li>Keep cats inside. Many shelters recommend this around Halloween, and some limit adoptions of black cats at this time of year as a precaution.</li>
<li>If you take your dog trick-or-treating, use a leash, a reflective collar or light, and head home if he seems anxious.</li>
</ul>

<h2>If Your Pet Eats Something Dangerous</h2>
<ol>
<li><strong>Remove what is left</strong> and keep the wrapper or packaging so you can say what it was and about how much was eaten.</li>
