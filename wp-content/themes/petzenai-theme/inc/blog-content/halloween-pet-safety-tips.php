<h2>The Halloween Pet Safety Checklist</h2>
<ol>
<li>Keep all candy in a closed cupboard or a high shelf, not in a bowl on the coffee table.</li>
<li>Never share candy with your pet, and tell children not to.</li>
<li>Choose costumes only if your pet likes them, and never leave a dressed-up pet alone.</li>
<li>Use LED candles instead of real flames, and tuck cords out of reach.</li>
<li>Put your pet in a quiet room with water, a bed and some chew toys while trick-or-treaters come and go.</li>
