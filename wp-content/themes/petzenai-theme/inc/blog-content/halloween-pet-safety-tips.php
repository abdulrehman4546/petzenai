<h2>Costumes: Safe or Not?</h2>
<p>Some pets enjoy dressing up, and many do not. A costume should never be forced on a pet that tries to wriggle out of it, hides or stops moving.</p>
<ul>
<li><strong>Check the fit.</strong> The costume should not squeeze the neck or chest, restrict movement, or cover the eyes, nose or ears.</li>
<li><strong>Avoid small parts.</strong> Buttons, bells and dangling pieces can be chewed off and swallowed.</li>
<li><strong>Skip masks and face paint.</strong> Pets can swallow paint, and masks can block vision and breathing.</li>
<li><strong>Practice first.</strong> Let your pet wear the costume for a few minutes at a time in the days before, with treats and praise.</li>
<li><strong>Stay with your pet.</strong> Take the costume off at the first sign of stress, or if your pet starts chewing it.</li>
<li><strong>Consider a simple alternative.</strong> A festive bandana is often easier for a pet than a full costume.</li>
</ul>

