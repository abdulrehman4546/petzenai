<h2>Frequently Asked Questions</h2>

<h3>Can dogs eat Halloween candy?</h3>
<p>No. Chocolate, sugar-free sweets that may contain xylitol, raisins and wrappers can all cause serious problems, and even harmless candy is high in sugar. Give your dog a pet-safe treat instead.</p>

<h3>Is a little chocolate okay for a big dog?</h3>
<p>It depends on the type and amount, and it is not worth guessing. Call your vet or a poison helpline and have the packaging ready, even if your dog is large.</p>

<h3>Is pumpkin safe for pets?</h3>
<p>Plain cooked pumpkin is generally safe in small amounts. Do not give pumpkin pie filling, which contains sugar and spices, and avoid old or mouldy pumpkins.</p>

<h3>How can I keep my dog calm on Halloween?</h3>
<p>Give your dog a quiet room away from the door, with a bed, water and a chew toy. Close curtains, add soft music or a fan, and take a walk earlier in the day so your dog is tired. If your dog is very anxious, talk to your vet well before next Halloween.</p>

