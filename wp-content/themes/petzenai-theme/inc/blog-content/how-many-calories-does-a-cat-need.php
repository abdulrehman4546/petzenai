<h2>What Changes for Kittens</h2>
<p>A growing kitten needs far more food for her size than an adult. Under four months she uses about 2.5 times her RER, and from four months to a year about twice her RER. For example, a 2 lb kitten under four months needs around 160 kcal a day, and a 5 lb kitten of eight months about 260 kcal.</p>
<ul>
<li>Feed a food made for kittens or for all life stages, and split it into three or four small meals.</li>
<li>Weigh her every week. Steady gain is the goal, and a kitten that stops gaining needs a vet check.</li>
<li>Her calorie needs per pound fall as she approaches a year old, so plan to review the amount monthly.</li>
</ul>

<h2>What Changes for Senior Cats</h2>
<p>This is where cats surprise people. Some cats slow down in middle age and gain weight, so they need fewer calories. But many cats over about 11 or 12 years old do the opposite. They lose weight and muscle, digest food less well, and may need <em>more</em> calories than a younger cat of the same size.</p>
<p>If an older cat is losing weight and you are not trying to make that happen, do not simply cut or raise her food. See your veterinarian, because unplanned weight loss can be an early sign of problems such as thyroid, kidney or dental disease.</p>

<h2>From Calories to Cups and Cans</h2>
<p>Calories are only useful once you know how many are in your cat’s food. The number is on the label as “kcal per cup” or “kcal per can”, and it varies a lot between brands. Dry foods are often 300 to 450 kcal per cup, and a 3 oz can of wet food is commonly 60 to 100 kcal.</p>
<p>The sum is simple: <strong>daily calories ÷ calories per cup (or can) = amount per day</strong>.</p>
<ul>
<li>A 10 lb cat needing 261 kcal on a 375 kcal per cup kibble gets about 0.7 cup a day.</li>
<li>The same cat on an 80 kcal can of wet food gets about 3.3 cans a day.</li>
<li>If you mix wet and dry, add up the calories from each so the total matches her target.</li>
</ul>
<p>Cups are not very precise, because a scoop of kibble can vary by 20 percent depending on how you fill it. A cheap kitchen scale and the kcal per gram on the bag give steadier portions.</p>

<h2>If Your Cat Needs to Lose Weight</h2>
<p>More than half of pet cats in the United States are overweight or obese, according to surveys by the Association for Pet Obesity Prevention. Extra weight is linked to diabetes, arthritis and a shorter life, so helping an overweight cat slim down is worth doing, but it has to be done slowly.</p>
<ul>
<li>A common starting point is about 80 percent of her RER. Vets often calculate it from her <em>ideal</em> weight, so ask your vet to estimate a target.</li>
<li>Aim to lose roughly 0.5 to 2 percent of her body weight a week. For a 14 lb cat that is about one to four ounces.</li>
<li><strong>Never crash-diet a cat.</strong> Cats that lose weight too fast, or stop eating, can develop a serious liver condition called hepatic lipidosis. If she stops eating for more than a day, call your vet.</li>
</ul>

<h2>Treats and Extras Count</h2>
<p>A widely used guideline is to keep treats to no more than about 10 percent of the day’s calories. For a cat on 260 kcal that is about 26 kcal, which is only a handful of small treats. Lickable pastes, toppers and table scraps all add up too. Count them, and take the same number of calories out of her meals.</p>

<h2>How to Tell You Are Feeding the Right Amount</h2>
<p>The formula gives you a number, but your cat tells you if it is right. Every two weeks:</p>
<ol>
<li><strong>Weigh her</strong> on the same scale. A baby scale works well. Or weigh yourself holding her and subtract your own weight.</li>
<li><strong>Feel her ribs.</strong> You should feel them under a thin layer of fat without pressing hard. If you cannot find them, she is carrying extra weight.</li>
<li><strong>Look from above.</strong> A healthy cat has a visible waist behind the ribs. From the side, her belly should tuck up slightly (not a low hanging pouch).</li>
<li><strong>Adjust by about 10 percent.</strong> If she is gaining when she should not be, trim her daily amount by about 10 percent. If she is losing, add 10 percent. Then check again in two weeks.</li>
</ol>

<h2>Common Mistakes</h2>
<ul>
<li><strong>Leaving a full bowl out all day.</strong> It is the easiest way to overfeed an indoor cat, because you cannot see how much she really eats. Two to four measured meals work better.</li>
<li><strong>Treating the feeding chart on the bag as a target.</strong> These charts are broad and often generous for neutered indoor cats.</li>
<li><strong>Assuming all cups have the same calories.</strong> One food can have more than 100 kcal per cup more than another.</li>
<li><strong>Forgetting treats.</strong> A few treats a day can quietly add 10 to 20 percent.</li>
<li><strong>Feeding several cats from one bowl.</strong> One cat often eats more than planned and another less. Feed them separately.</li>
</ul>

<h2>When to Talk to Your Vet</h2>
<p>These numbers are for healthy cats. Talk to a veterinarian before changing the diet if your cat has a health condition such as diabetes, kidney disease or hyperthyroidism, if she is pregnant or nursing, if she is losing weight without a diet, or if her appetite suddenly changes.</p>

<h2>Frequently Asked Questions</h2>

<h3>How many calories should a 10 lb cat eat?</h3>
<p>A healthy neutered 10 lb cat usually needs about 215 to 260 calories a day, depending on how active she is. An intact cat of the same weight needs closer to 305.</p>

<h3>How many calories does a kitten need?</h3>
<p>Much more per pound than an adult. A kitten under four months needs about 2.5 times her resting energy requirement, and a kitten of four to twelve months about twice. A 2 lb kitten needs around 160 calories a day.</p>

<h3>Is wet food or dry food better for calories?</h3>
<p>Neither is automatically lower or higher. Wet food is mostly water, so you feed more of it by weight for the same calories. Always use the kcal on the label of the food you actually feed.</p>

<h3>How often should I recalculate my cat’s calories?</h3>
<p>Monthly for kittens, and every few months for adults. Do it again whenever her weight, activity or neuter status changes.</p>

