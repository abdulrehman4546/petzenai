<h2>Pets on Medication: Ask Your Vet First</h2>
<p>This is the one situation where you should not shift times on your own. Pets that take medication at set intervals, such as insulin for diabetes, seizure medication or some heart and thyroid medicines, rely on a steady schedule. Changing the timing by an hour can matter. Ask your vet how to handle the time change before it happens, and never change a dose or its timing without their advice.</p>

