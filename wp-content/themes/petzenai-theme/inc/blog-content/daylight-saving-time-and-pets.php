<h2>Why Pets Notice the Time Change</h2>
<p>Pets tell time by their routine and by light. If you normally feed dinner at 6 p.m., their body expects it at that point. After the clocks go back, “6 p.m.” on the clock feels to your pet like 7 p.m., and they will start asking for dinner an hour early. Dogs usually adjust fast, but the meal times are the part they notice most, and cats are often more set in their ways.</p>

<h2>A Simple Plan: Shift Later by 10 to 15 Minutes a Day</h2>
<p>When the clock goes back, your pet’s routine needs to move <strong>later</strong>, so it fits the new time. Start about a week before. Each day, move feeding, walks and play 10 to 15 minutes later than the day before.</p>

