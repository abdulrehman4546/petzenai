<p>Once the clocks go back, sunset arrives an hour earlier by the clock, so many evening walks now happen in the dark. Make sure you and your pet are visible:</p>
<ul>
<li>Use a reflective collar, harness or leash, or a clip-on light.</li>
<li>Wear reflective clothing or carry a torch yourself.</li>
<li>Keep your dog on a leash near roads, and choose well-lit routes.</li>
<li>Take the main walk when it is light if you can, for example at lunchtime or in the early morning.</li>
</ul>

<h2>Use Light to Help the Body Clock</h2>
<p>Light is a powerful cue. Open the curtains in the morning to let in daylight, and dim the lights in the evening. A walk or playtime in natural light early in the day helps your pet’s body clock settle faster.</p>

<h2>When to Talk to Your Vet</h2>
<p>Most pets adapt within a week. Talk to your vet if your pet stops eating, has bathroom accidents, seems unusually anxious, or if the change in routine lasts more than a week or so. These can be signs of something other than the time change.</p>

<h2>Frequently Asked Questions</h2>

<h3>Do pets get jet lag from the time change?</h3>
<p>Not exactly, but they feel the mismatch between their routine and the new clock, which can cause early waking, hunger and restlessness for a few days.</p>

<h3>Should I change my pet’s feeding time when the clocks change?</h3>
<p>It is best to shift it gradually, by 10 to 15 minutes a day, rather than all at once. For pets on medication, ask your vet first.</p>

<h3>How long does it take a pet to adjust?</h3>
<p>Most take a few days to a week. Cats and older or anxious pets may need longer.</p>

<h3>My dog wakes me up an hour early. What can I do?</h3>
<p>Do not reward the early wake-up with food or play. Shift his routine later gradually, and make the room darker and quieter in the morning.</p>

