<p>It usually happens out of nowhere. Your cat stops, plants her feet, stretches her neck forward, and starts pulling air in through her nose in quick, loud snorts. It sounds like choking, or like she's about to throw up. A few seconds later it stops, and she walks off as if nothing happened.</p>

<p>That's a reverse sneeze. A normal sneeze pushes air out of the nose to clear an irritant. A reverse sneeze pulls air in, fast and hard, to do the same job. PetMD describes the throat squeezing and the mouth muscles spasming during an episode, which makes a full breath hard to take. So you get a string of short, noisy inhales.</p>

<p>Our broader post on <a href="/blog/dog-cat-coughing-reverse-sneezing/">dog reverse sneezing and coughing</a> covers the dog version, and how a reverse sneeze differs from a true cough. Cats only get a short paragraph there. This is the longer cat version, and cats need one for two reasons. They reverse sneeze less often than dogs (PetMD says so directly), so fewer owners recognize it. And its most important lookalike, an asthma cough, is mostly a cat problem.</p>

<h2>During the Episode: What You're Seeing</h2>

<p>Based on PetMD's description:</p>

<p><strong>The sound</strong> is snorting or honking, made of quick, short breaths repeated for several seconds. It's an inhale. The noise is being pulled in through the nose, not pushed out through the mouth.</p>

<p><strong>The posture</strong> is a stretched-out neck, sometimes with the throat looking sucked in. PetMD notes it can look like the cat is trying to vomit.</p>

<p><strong>How long it lasts:</strong> usually under a minute, though PetMD admits it feels much longer when you're watching. It starts suddenly and stops on its own.</p>

<p>Usually the best thing to do is nothing. PetMD mentions a few things that may shorten an episode: gently rubbing the throat, blowing softly at her face, or covering the nostrils for a couple of seconds so she swallows. Those are fine with a relaxed cat. With a cat who hates being held, grabbing her mid-snort is more likely to get you scratched than to help. The episode will end without you.</p>

<p><strong>What is worth doing:</strong> recording it on your phone. PetMD points out that cats almost never do this on the exam table, so a video is the most useful thing you can bring your vet. It also helps answer the next question.</p>

<h2>Is It Really a Reverse Sneeze? Three Lookalikes</h2>

<h3>An asthma cough (the one that matters most in cats)</h3>

<p>Cornell Feline Health Center describes a posture many cats take during an asthma attack: body hunched close to the ground, neck stretched forward. That looks a lot like a reverse sneeze. Cornell puts asthma at 1 to 5% of cats, usually diagnosed around age 4 to 5.</p>

<p>The difference is which way the air moves, and how she breathes afterward. A reverse sneeze is a noisy pull <em>in</em> through the nose. An asthma cough is a hack pushed <em>out</em>, and Cornell lists wheezing, rapid breathing, and open-mouthed breathing among the signs. If the episode ends with your cat still crouched and breathing fast, or breathing through her mouth, it probably wasn't a reverse sneeze. PetMD gives the same advice: if you're not sure, check with your vet so asthma doesn't get missed. X-rays can help tell the two apart.</p>

<h3>A hairball</h3>

<p>Hairball retching comes from the belly. You'll see the abdomen heave and hear a wet "ack," and something usually comes up, or she clearly tries to bring something up. A reverse sneeze stays in the nose and throat, and nothing comes up.</p>

<h3>Real choking</h3>

<p>This one is never wait-and-see. PetMD notes that reverse sneezing can resemble choking or difficulty breathing, and that those are emergencies. Signs it's a real airway problem and not a reverse sneeze:</p>

<ul>
<li>It doesn't stop after a minute or two, or keeps starting again right away.</li>
<li>She's pawing at her mouth or panicking.</li>
<li>She's breathing with her mouth open or straining.</li>
<li>Her gums or tongue look pale, gray, or blue.</li>
<li>She collapses or seems weak afterward.</li>
</ul>

<p>Any of those means calling a vet or emergency clinic right away. It's worth reading our <a href="/tools/pet-first-aid-guide/">pet first aid guide</a> now, so you aren't seeing it for the first time in a panic.</p>

<h2>Right After: What Set It Off?</h2>

<p>A true reverse sneeze ends with a normal cat. Once it's over, look around, because the trigger is often nearby. PetMD's list of common triggers includes:</p>

<ul>
<li>Dust or pollen</li>
<li>Perfume, smoke, or other strong scents</li>
<li>A blade of grass or a plant bristle</li>
<li>Eating or drinking too fast</li>
<li>Getting overexcited</li>
<li>A recent intranasal vaccine</li>
</ul>

<p>Make a note of what she was doing just before. PetMD suggests passing exactly that on to your vet, and after a few episodes there's often a pattern. If it always follows the air freshener, you have your answer.</p>

<p>Then watch her breathing once she settles. Cornell says a cat's resting breathing shouldn't go above 35 breaths per minute. Slow, easy breaths through the nose fit a reverse sneeze.</p>

<h2>Over the Following Weeks: When the Pattern Is the Problem</h2>

<p>One episode tells you very little. Repeat episodes tell you more. PetMD's list also includes causes that aren't in the air: nasal polyps, upper respiratory infections, rhinitis (inflammation inside the nose), nasal mites, and the narrowed airways of flat-faced breeds like Persians and Himalayans. These are the reasons a cat reverse sneezes again and again.</p>

<h3>Nasopharyngeal polyps</h3>

<p>Polyps are worth knowing about because they're largely a cat problem. VCA describes them as benign growths that start in the middle ear and grow down the tube connecting the ear to the back of the throat. There they can partly block airflow. VCA lists a distinctive snorting sound when breathing, sneezing, and clear or bloody nasal discharge among the signs. If the polyp grows toward the ear instead, you may see head shaking, pawing at an ear, or a head tilt.</p>

<p>VCA says polyps are most common in young cats, often under a year old. So a kitten who snorts a lot, especially with nasal discharge or ear signs, should see a vet. Surgery to remove a polyp usually improves breathing, though VCA notes they often grow back.</p>

<h3>Lingering respiratory infections</h3>

<p>Cornell estimates that up to 80% of cats exposed to feline herpesvirus carry it for life, and some get repeated flare-ups of upper respiratory signs, often when stressed. If her snorting comes in clusters along with sneezing, eye discharge, or a runny nose, that kind of recurring irritation is a likelier cause than random dust.</p>

<h3>When to book an appointment</h3>

<p>A routine (not emergency) vet visit makes sense when:</p>

<ul>
<li>It's the first time you've seen anything like it and you aren't sure what it was. PetMD recommends this too.</li>
<li>Episodes are getting more frequent or lasting longer.</li>
<li>There's nasal discharge, especially if it's bloody.</li>
<li>You notice head shaking or a head tilt along with the snorting.</li>
<li>She breathes noisily even between episodes.</li>
<li>Her appetite or energy has dropped.</li>
</ul>

<p>Bring the video and your notes on triggers. If episodes are frequent and the cause isn't obvious, PetMD says a vet may sedate the cat to examine the nose and throat properly, sometimes with a tiny camera (rhinoscopy). Treatment depends on what turns up. Most cats who reverse sneeze now and then never need any.</p>

<h2>The Short Version</h2>

<p>A snort pulled in through the nose that lasts under a minute, followed by calm breathing and normal behavior, is almost always a reverse sneeze. Get a video, look for the trigger, and book a routine visit if it keeps happening. Open-mouth breathing, a change in gum color, panic, or an episode that won't stop is an emergency.</p>

