<h2>Frequently Asked Questions</h2>

<h3>Can dogs eat turkey?</h3>
<p>Yes, plain cooked turkey meat without skin, bones, seasoning or gravy is fine in small amounts.</p>

<h3>Can cats eat turkey?</h3>
<p>Yes. Cats are carnivores, and a few bites of plain, cooked, unseasoned turkey are fine. Keep it small so it does not replace their balanced meals.</p>

<h3>Can dogs eat stuffing?</h3>
<p>No. Stuffing often contains onion, garlic and a lot of fat, and the safest choice is to avoid it completely.</p>

<h3>Is pumpkin pie safe for pets?</h3>
<p>No. Pie filling contains sugar, spices and sometimes xylitol or chocolate. Plain canned pumpkin without additives is a better choice in small amounts.</p>

<h3>What should I do if my dog ate turkey bones?</h3>
<p>Call your veterinarian straight away, even if he seems fine. Bones can cause damage inside that is not obvious at first. Do not try to make him vomit.</p>

