<h2>The Biggest Thanksgiving Risks</h2>
<h3>Bones, Skin and Fat</h3>
<p>The turkey carcass is the classic Thanksgiving danger. Cooked bones can splinter and cause choking, injuries or a blockage. Skin, drippings and gravy are very high in fat, which can inflame the pancreas (pancreatitis). Signs include vomiting, belly pain, diarrhea, tiredness and not wanting to eat, often in the day or two after the meal. See a vet if you notice them.</p>

<h3>Stuffing and Hidden Onion and Garlic</h3>
<p>Stuffing is usually made with onions, garlic and a lot of butter. These ingredients are harmful to dogs and cats. They are also in many gravies, casseroles and side dishes, so check the ingredients before offering a taste.</p>

<h3>Desserts and Sweeteners</h3>
<p>Chocolate is toxic to pets. Sugar-free desserts and some sweeteners can contain xylitol, which is very dangerous for dogs. Raisins in baking can cause kidney problems. Pies are also high in sugar, fat and spices, so keep every dessert out of reach.</p>

<h3>The Trash Can</h3>
<p>Many Thanksgiving emergencies start in the bin. A carcass, string, foil and fat-soaked paper are all tempting. Take the rubbish out to a closed bin straight after the meal, and keep leftovers in the fridge.</p>

