<h2>How to Bathe a Dog Safely</h2>
<ol>
<li><strong>Brush first.</strong> Remove tangles and loose hair before the coat gets wet, because water tightens mats.</li>
<li><strong>Use lukewarm water.</strong> Test it on your wrist. Wet the whole coat down to the skin, keeping water out of the ears and eyes.</li>
<li><strong>Use dog shampoo.</strong> Dog skin is less acidic than human skin, and human shampoos can dry and irritate it. Dilute concentrated shampoos and work them in from the neck back.</li>
<li><strong>Rinse thoroughly.</strong> Shampoo left on the skin is a common cause of itching. Rinse until the water runs clear, then rinse once more.</li>
<li><strong>Dry well.</strong> Towel dry, and for long or thick coats use a dryer on a cool or low-heat setting while you brush. Damp fur can lead to skin problems.</li>
<li><strong>Finish on a high note.</strong> Praise and a treat help dogs accept the next bath.</li>
</ol>

<h2>Between Baths</h2>
<ul>
<li>Brush regularly. It spreads natural oils and removes dirt, and often means fewer baths are needed.</li>
<li>Wipe muddy paws and bellies with a damp cloth after walks.</li>
<li>Rinse with plain water after muddy or sandy walks. A quick rinse does not count as a full shampoo bath.</li>
<li>Wash bedding every week or two. A clean dog on dirty bedding smells again quickly.</li>
</ul>

