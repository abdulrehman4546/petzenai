<h2>What Makes the Interval Shorter or Longer</h2>
<p>Start with the number for your dog’s coat, then adjust:</p>
<ul>
<li><strong>Lifestyle.</strong> A mostly indoor dog can go a week or so longer. A dog that is often muddy or wet may need a bath about three weeks sooner, and plain-water rinses in between.</li>
<li><strong>Season.</strong> In hot, humid weather dogs get dirtier and smellier faster, so you may bathe slightly more often. In cold, dry weather, air and heating dry out the skin, so you can stretch the gap.</li>
<li><strong>Skin.</strong> Dogs with dry or sensitive skin often do better with fewer baths and a moisturising, gentle shampoo. Oily skin and a doggy odour usually mean the interval should be shorter.</li>
<li><strong>Allergies.</strong> Bathing can wash allergens and pollen off the coat, so some dogs with environmental allergies benefit from more frequent baths. Follow your vet’s advice on this.</li>
</ul>

<p>As worked examples, our calculator gives about 5 to 7 weeks for a short-coated dog with a normal outdoor lifestyle, 2 to 4 weeks for the same dog if he is constantly muddy, and about 8 to 10 weeks for a double-coated dog who lives mostly indoors.</p>

<h2>Puppies</h2>
<p>Very young puppies are not good at keeping themselves warm, so a full bath is not a good idea for puppies under about 12 weeks. Spot-clean with a damp, warm cloth, and check with your veterinarian before the first real bath. After that, puppies can follow the same schedule as adults, using a gentle puppy shampoo and making bath time calm and positive.</p>

