<li><strong>Hairless dogs.</strong> Their bare skin needs regular cleaning, and also protection from sun and dryness. Ask your vet which pet-safe products to use.</li>
<li><strong>Dogs with skin conditions.</strong> Medicated shampoos have specific instructions, sometimes as often as weekly. Follow your vet’s plan, not a general schedule.</li>
</ul>

<h2>Frequently Asked Questions</h2>

<h3>Can I bathe my dog every week?</h3>
<p>Some dogs, such as hairless breeds or dogs on a vet-directed plan, do. For most healthy dogs, weekly shampoo baths are too often and can dry the skin. If your dog gets very dirty, use plain-water rinses between full baths.</p>

<h3>Is it okay to bathe a dog once a year?</h3>
<p>Some low-maintenance short-coated dogs can go a long time, but most owners find a bath every one to two months keeps odour and dirt under control. If your dog does not smell, is not greasy and has a healthy coat, you can stretch the interval.</p>

<h3>Should I brush before or after a bath?</h3>
<p>Both. Brush before to remove tangles and loose hair, and brush again as the coat dries to keep it smooth.</p>

